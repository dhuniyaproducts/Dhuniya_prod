-- ========================================================
-- Dhuniya Products Database Schema (Supabase PostgreSQL)
-- Run this in your Supabase SQL Editor:
-- ========================================================

-- Enable UUID extension if needed
create extension if not exists "uuid-ossp";

-- 1. PRODUCTS TABLE
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  unit text not null default 'kg',
  price numeric not null,
  active boolean not null default true,
  image_url text,
  description text,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Migration if table already exists
alter table public.products add column if not exists description text;

-- 2. ORDERS TABLE
create table if not exists public.orders (
  id text primary key,
  date date not null default current_date,
  delivery_date date not null,
  customer text not null,
  product_id bigint references public.products(id) on delete set null,
  qty numeric not null,
  rate numeric,
  status text not null default 'Pending',
  notes text,
  phone text,
  address text,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Migrations if table already exists
alter table public.orders add column if not exists phone text;
alter table public.orders add column if not exists address text;
alter table public.orders add column if not exists items jsonb;
alter table public.orders add column if not exists amount_paid numeric default 0;
alter table public.orders add column if not exists payment_status text default 'Unpaid';

-- 3. CUSTOMERS TABLE (Customer directory & auto-saves customer names for dropdown reuse)
create table if not exists public.customers (
  id bigint generated by default as identity primary key,
  name text not null unique,
  phone text,
  address text,
  notes text,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Migrations if table already exists
alter table public.customers add column if not exists phone text;
alter table public.customers add column if not exists address text;
alter table public.customers add column if not exists notes text;

-- 4. ROW LEVEL SECURITY (RLS)
-- Enable RLS
alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.customers enable row level security;

-- Drop existing policies if any
drop policy if exists "Allow all access to products" on public.products;
drop policy if exists "Allow all access to orders" on public.orders;
drop policy if exists "Authenticated full access customers" on public.customers;
drop policy if exists "Public read customers" on public.customers;

-- CUSTOMERS policies
create policy "Authenticated full access customers" on public.customers
  for all using (auth.role() = 'authenticated') with check (auth.role() = 'authenticated');
create policy "Public read customers" on public.customers
  for select using (true);
drop policy if exists "Public read products" on public.products;
drop policy if exists "Authenticated full access products" on public.products;
drop policy if exists "Authenticated full access orders" on public.orders;
drop policy if exists "Authenticated insert products" on public.products;
drop policy if exists "Authenticated update products" on public.products;
drop policy if exists "Authenticated delete products" on public.products;

-- PUBLIC: Anyone can read active products (for the public homepage)
create policy "Public read products" on public.products
  for select using (true);

-- AUTHENTICATED: Logged-in users can do full CRUD on products
create policy "Authenticated insert products" on public.products
  for insert with check (auth.role() = 'authenticated');

create policy "Authenticated update products" on public.products
  for update using (auth.role() = 'authenticated');

create policy "Authenticated delete products" on public.products
  for delete using (auth.role() = 'authenticated');

-- AUTHENTICATED: Logged-in users can do full CRUD on orders
create policy "Authenticated full access orders" on public.orders
  for all using (auth.role() = 'authenticated') with check (auth.role() = 'authenticated');

